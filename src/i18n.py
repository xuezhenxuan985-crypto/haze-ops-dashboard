def tr(key: str, lang: str = "en", **fmt) -> str:
    """Translate key into lang, formatting named placeholders."""
    table = STRINGS.get(lang, STRINGS["en"])
    s = table.get(key, STRINGS["en"].get(key))
    if s is None:
        return f"[{key}]"
    try:
        return s.format(**fmt)
    except (KeyError, IndexError, ValueError):
        return f"[{key}:fmt]"
